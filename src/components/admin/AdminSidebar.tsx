interface AdminSidebarProps {
  onClose?: () => void;
}

export function AdminSidebar({ onClose }: AdminSidebarProps) {
  const pathname = usePathname();

  function isActive(href: string, exact?: boolean) {
    if (exact) return pathname === href;
    return pathname.startsWith(href);
  }

  return (
    <aside className="w-60 bg-[#111111] border-r border-[#2a2a2a] flex flex-col h-full">
      <div className="p-5 border-b border-[#2a2a2a]">
        <span className="text-[#ffd600] font-bold text-base tracking-wide uppercase">
          Norte Admin
        </span>
      </div>

      <nav className="flex-1 py-4 overflow-y-auto">
        <ul className="space-y-0.5 px-3">
          {navItems.map((item) => {
            const active = isActive(item.href, item.exact);
            return (
              <li key={item.href}>
                <Link
                  href={item.href}
                  onClick={onClose}
                  className={`flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm font-medium transition-colors ${
                    active
                      ? "bg-[#ffd600]/10 text-[#ffd600]"
                      : "text-[#9ca3af] hover:bg-[#1a1a1a] hover:text-white"
                  }`}
                >
                  <span className={active ? "text-[#ffd600]" : "text-[#6b7280]"}>
                    {item.icon}
                  </span>
                  {item.label}
                </Link>
              </li>
            );
          })}
        </ul>
      </nav>
    </aside>
  );
}
